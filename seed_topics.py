async def main():
    await init_db()

    async with async_session() as session:
        result = await session.execute(select(Topic.title))
        existing = {row[0] for row in result.all()}

        added = 0
        for title in TOPICS:
            if title not in existing:
                session.add(Topic(title=title, is_active=False))
                added += 1

        await session.commit()

    print(f"✅ Добавлено новых тем: {added}")
    print(f"⏭️  Уже было (пропущено): {len(TOPICS) - added}")
    print(f"📚 Всего тем в базе: {len(existing) + added}")


if __name__ == "__main__":
    asyncio.run(main())
